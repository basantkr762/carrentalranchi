// Helper to compute estimated fares
function calcFares(distKm) {
  const d = parseInt(distKm);
  const sedanOW = Math.round(d*9/100)*100 < 1500 ? 1500 : Math.round(d*9/100)*100;
  const suvOW = Math.round(d*11/100)*100 < 2000 ? 2000 : Math.round(d*11/100)*100;
  const crystaOW = Math.round(d*13/100)*100 < 2500 ? 2500 : Math.round(d*13/100)*100;
  return {
    sedanOW: sedanOW.toLocaleString('en-IN'),
    suvOW: suvOW.toLocaleString('en-IN'),
    crystaOW: crystaOW.toLocaleString('en-IN'),
    sedanRT: (Math.round(sedanOW*1.8/100)*100).toLocaleString('en-IN'),
    suvRT: (Math.round(suvOW*1.8/100)*100).toLocaleString('en-IN'),
    crystaRT: (Math.round(crystaOW*1.8/100)*100).toLocaleString('en-IN'),
  };
}

// Time estimate from distance
function estimateTime(distKm) {
  const d = parseInt(distKm);
  if (d <= 50) return '1–1.5 hrs';
  if (d <= 100) return '2–2.5 hrs';
  if (d <= 150) return '2.5–3.5 hrs';
  if (d <= 200) return '3.5–4.5 hrs';
  if (d <= 300) return '5–6 hrs';
  if (d <= 400) return '6–8 hrs';
  if (d <= 500) return '8–10 hrs';
  return '10–12 hrs';
}

