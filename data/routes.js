// Generate route objects from pairs
function generateRoutes() {
  const routes = [];
  routePairs.forEach(([fromSlug, toSlug, distKm, highlights, roadDesc]) => {
    const fares = calcFares(distKm);
    const time = estimateTime(distKm);
    // Forward route
    routes.push({
      fromSlug, toSlug,
      slug: `${fromSlug}-to-${toSlug}-cab`,
      dist: `${distKm} km`,
      distKm,
      time,
      highlights,
      roadDesc,
      ...fares
    });
    // Reverse route
    routes.push({
      fromSlug: toSlug, toSlug: fromSlug,
      slug: `${toSlug}-to-${fromSlug}-cab`,
      dist: `${distKm} km`,
      distKm,
      time,
      highlights,
      roadDesc,
      ...fares
    });
  });
  return routes;
}

module.exports = { generateRoutes, routePairs, calcFares, estimateTime };
